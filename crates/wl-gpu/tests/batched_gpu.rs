const RT: usize = 0x8000;
const SIZE: usize = 208 * 29;
const BG: [u8; 4] = [11, 17, 23, 255];
const POS: [[[f32; 2]; 3]; 3] = [
    [[-0.9, -0.8], [0.6, -0.6], [-0.5, 0.85]],
    [[-0.5, -0.7], [0.9, 0.1], [-0.1, 0.8]],
    [[-0.4, -0.8], [0.75, -0.5], [0.1, 0.65]],
];
fn method(w: &mut Vec<u32>, m: u32, v: u32) {
    w.extend([0x20010000 | (m / 4), v]);
}
fn geometry(data: &mut [u8]) {
    for (n, p) in POS.iter().flatten().enumerate() {
        // Third triangle has an actual varying UV generated by the guest VS.
        let uv = [[0.1, 0.2], [0.9, 0.1], [0.25, 0.85]][n % 3];
        for (c, v) in [p[0], p[1], 0., 1., uv[0], uv[1]].iter().enumerate() {
            data[0x3000 + n * 24 + c * 4..0x3004 + n * 24 + c * 4]
                .copy_from_slice(&v.to_le_bytes());
        }
    }
}
fn edge(a: [f64; 2], b: [f64; 2], p: [f64; 2]) -> f64 {
    (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])
}
fn check(pixels: &[u8], image: &[u8]) {
    let mut counts = [0usize; 4];
    for y in 0..29 {
        for x in 0..52 {
            let p = [
                (x as f64 + 0.5) * 2. / 47. - 1.,
                1. - (y as f64 + 0.5) * 2. / 29.,
            ];
            let mut expected = BG;
            let mut layer = 0;
            let mut ambiguous = false;
            for (n, pos) in POS.iter().enumerate() {
                let v = pos.map(|p| p.map(f64::from));
                let area = edge(v[0], v[1], v[2]);
                let b = [
                    edge(v[1], v[2], p) / area,
                    edge(v[2], v[0], p) / area,
                    edge(v[0], v[1], p) / area,
                ];
                if b.iter().any(|v| v.abs() < 0.005) {
                    ambiguous = true;
                }
                if x >= 47 || b.iter().any(|v| *v < 0.) {
                    continue;
                }
                expected = match n {
                    0 => [64, 128, 191, 255],
                    1 => [255, 0, 0, 255],
                    _ => {
                        let u = (b[0] * 0.1 + b[1] * 0.9 + b[2] * 0.25) * 37.;
                        let v = (b[0] * 0.2 + b[1] * 0.1 + b[2] * 0.85) * 19.;
                        if (u - u.round()).abs() < 0.02 || (v - v.round()).abs() < 0.02 {
                            ambiguous = true;
                        }
                        let i = (v.floor().clamp(0., 18.) as usize * 37
                            + u.floor().clamp(0., 36.) as usize)
                            * 4;
                        image[i..i + 4].try_into().unwrap()
                    }
                };
                layer = n + 1;
            }
            if ambiguous {
                continue;
            }
            let actual = &pixels[(y * 52 + x) * 4..(y * 52 + x + 1) * 4];
            for c in 0..4 {
                assert!(
                    actual[c].abs_diff(expected[c]) <= 1,
                    "{x},{y}: {actual:?}!={expected:?}, layer{layer}"
                );
            }
            counts[layer] += 1;
        }
    }
    assert!(counts[0] > 700);
    assert!(
        counts[1] > 20 && counts[2] > 20 && counts[3] > 100,
        "{counts:?}"
    );
}
fn fixture() -> (Vec<u8>, AddressMap, Vec<u32>, Vec<u8>) {
    let desc = TextureImage::decode(TIC_RGBA)
        .unwrap()
        .with_sampler(TextureSampler::decode(TSC_NEAREST).unwrap());
    let (surface, image) = rgba_surface(desc);
    let mut data = vec![0; 0xe000];
    data[..64].copy_from_slice(&descriptor_bytes(TIC_RGBA, TSC_NEAREST));
    data[0x1000..0x1000 + surface.len()].copy_from_slice(&surface);
    for (off, b) in [
        (
            0x4000,
            include_bytes!("fixtures/maxwell/tex.bin").as_slice(),
        ),
        (
            0x4100,
            include_bytes!("fixtures/maxwell/quarters.bin").as_slice(),
        ),
        (
            0x4200,
            include_bytes!("fixtures/maxwell/vertex.bin").as_slice(),
        ),
        (
            0x4400,
            include_bytes!("fixtures/maxwell/red.bin").as_slice(),
        ),
    ] {
        data[off..off + b.len()].copy_from_slice(b);
    }
    geometry(&mut data);
    for rt in [RT, 0xb000] {
        for p in data[rt..rt + SIZE].chunks_exact_mut(4) {
            p.copy_from_slice(&BG);
        }
    }
    let mut map = AddressMap::default();
    for (g, a, n) in [
        (0x10000, 0x1000, surface.len() as u64),
        (0x30000, 0, 32),
        (0x31000, 32, 32),
        (0x40000, 64, 32),
        (0x50000, 0x4000, 0x1000),
        (0x70000, 0x3000, 216),
        (0x90000, RT as u64, SIZE as u64),
        (0xa0000, 0xb000, SIZE as u64),
        (0xc0000, RT as u64, SIZE as u64),
    ] {
        map.map(GpuAddress(g), GuestAddress(a), n).unwrap();
    }
    let mut words = common::hardware::setup();
    method(&mut words, 0x1f04, 0x700d7);
    for (offset, first) in [(0x100, 0), (0x400, 3), (0, 6)] {
        method(&mut words, 0x2144, offset);
        method(&mut words, 0x1214, 0x40030000 | first);
    }
    (data, map, words, image[0].clone())
}
fn deferred(
    r: &mut Renderer,
    c: &mut Channel,
    w: &[u32],
    m: &AddressMap,
    data: &mut [u8],
    changes: &mut TextureChanges,
) -> u64 {
    r.submit_pushbuffer_deferred(
        c,
        w,
        m,
        &mut SliceMemoryMut {
            base: GuestAddress(0),
            bytes: data,
        },
        changes,
    )
    .unwrap()
}
fn sync(r: &mut Renderer, data: &mut [u8], changes: &mut TextureChanges) -> wl_gpu::backend::Frame {
    r.synchronize_target(
        &mut SliceMemoryMut {
            base: GuestAddress(0),
            bytes: data,
        },
        changes,
    )
    .unwrap()
    .unwrap()
}
#[test]
#[ignore = "requires actual GPU; run explicitly"]
fn ordered_multi_draw_one_readback_and_cpu_visibility() {
    let (mut data, map, words, image) = fixture();
    let mut changes = TextureChanges::new(1);
    let mut r = Renderer::new().unwrap();
    let mut c = Channel::default();
    let start = std::time::Instant::now();
    assert_eq!(
        deferred(&mut r, &mut c, &words, &map, &mut data, &mut changes),
        3
    );
    let submit_time = start.elapsed();
    assert_eq!(r.counters.submissions, 3);
    assert_eq!(r.counters.synchronization_points, 0);
    assert_eq!(r.counters.readback_bytes, 0);
    assert_eq!(r.counters.render_target_upload_bytes, SIZE as u64);
    assert_eq!(r.counters.render_target_allocations, 1);
    for p in data[RT..RT + SIZE].chunks_exact(4) {
        assert_eq!(p, BG);
    }
    let frame = sync(&mut r, &mut data, &mut changes);
    check(&frame.rgba, &image);
    assert_eq!(&data[RT..RT + SIZE], frame.rgba);
    assert_eq!(r.counters.readback_operations, 1);
    assert_eq!(r.counters.synchronization_points, 1);
    assert_eq!(r.counters.guest_framebuffer_write_bytes, SIZE as u64);
    assert!(
        r.synchronize_target(
            &mut SliceMemoryMut {
                base: GuestAddress(0),
                bytes: &mut data
            },
            &mut changes
        )
        .unwrap()
        .is_none()
    );
    println!(
        "backend={:?} three_draw_submit={submit_time:?} completion={:?} counters={:?}",
        r.capabilities.adapter, frame.total_time, r.counters
    );
    // Warm resource-preserving sequence: 32 draws, one visibility boundary.
    let before = r.counters;
    let region = Region::new(ALLOCATOR);
    let start = std::time::Instant::now();
    for _ in 0..32 {
        deferred(
            &mut r,
            &mut c,
            &[0x20010485, 0x40030006],
            &map,
            &mut data,
            &mut changes,
        );
    }
    let submit = start.elapsed();
    let allocations = region.change();
    assert_eq!(r.counters.readback_operations, before.readback_operations);
    assert_eq!(
        r.counters.synchronization_points,
        before.synchronization_points
    );
    assert_eq!(r.counters.upload_bytes, before.upload_bytes);
    assert_eq!(r.counters.pipeline_allocations, before.pipeline_allocations);
    assert_eq!(r.counters.shader_binary_bytes, before.shader_binary_bytes);
    assert_eq!(r.counters.descriptor_reads, before.descriptor_reads);
    let frame = sync(&mut r, &mut data, &mut changes);
    check(&frame.rgba, &image);
    println!(
        "warm32 submit={submit:?} Rust_allocations={allocations:?} readback_bytes={} waits={} submissions={}",
        r.counters.readback_bytes - before.readback_bytes,
        r.counters.synchronization_points - before.synchronization_points,
        r.counters.submissions - before.submissions
    );
    // An aliased VA preserves the pending target. CPU patch overlaps GPU output;
    // exact declared bytes win while every untouched GPU pixel survives.
    let mut draw = Vec::new();
    method(&mut draw, 0x804, 0xc0000);
    method(&mut draw, 0x1214, 0x40030006);
    let before = r.counters;
    deferred(&mut r, &mut c, &draw, &map, &mut data, &mut changes);
    assert_eq!(
        r.counters.render_target_upload_bytes,
        before.render_target_upload_bytes
    );
    let patch = (14 * 52 + 23) * 4;
    data[RT + patch..RT + patch + 4].copy_from_slice(&[1, 2, 3, 4]);
    changes
        .mark_write(GuestAddress((RT + patch) as u64), 4)
        .unwrap();
    let mut expected = frame.rgba.clone();
    expected[patch..patch + 4].copy_from_slice(&[1, 2, 3, 4]);
    let merged = sync(&mut r, &mut data, &mut changes);
    assert_eq!(merged.rgba, expected);
    // A later draw must upload merged CPU data, without recompiling the shader.
    let before = r.counters;
    deferred(&mut r, &mut c, &draw, &map, &mut data, &mut changes);
    assert_eq!(r.counters.pipeline_allocations, before.pipeline_allocations);
    assert_eq!(
        r.counters.render_target_upload_bytes - before.render_target_upload_bytes,
        SIZE as u64
    );
    // Fault after successful submission leaves pending work available for explicit sync.
    assert!(
        r.submit_pushbuffer_deferred(
            &mut c,
            &[0x20010485, 0x40020000],
            &map,
            &mut SliceMemoryMut {
                base: GuestAddress(0),
                bytes: &mut data
            },
            &mut changes
        )
        .is_err()
    );
    let recovered = sync(&mut r, &mut data, &mut changes);
    check(&recovered.rgba, &image);
}
#[test]
#[ignore = "requires actual GPU; run explicitly"]
fn pending_rebind_cpu_write_barrier_and_lost_journal_rejection() {
    let (mut data, map, words, _image) = fixture();
    let mut changes = TextureChanges::new(1);
    let mut r = Renderer::new().unwrap();
    let mut c = Channel::default();
    deferred(&mut r, &mut c, &words, &map, &mut data, &mut changes);
    let patch = (14 * 52 + 23) * 4;
    data[RT + patch..RT + patch + 4].copy_from_slice(&[1, 2, 3, 4]);
    changes
        .mark_write(GuestAddress((RT + patch) as u64), 4)
        .unwrap();
    // Target rebind flushes the old image and preserves the late CPU patch.
    let mut rebind = Vec::new();
    method(&mut rebind, 0x804, 0xa0000);
    method(&mut rebind, 0x1214, 0x40030006);
    deferred(&mut r, &mut c, &rebind, &map, &mut data, &mut changes);
    assert_eq!(&data[RT + patch..RT + patch + 4], [1, 2, 3, 4]);
    assert_eq!(r.counters.coherence_barriers, 1);
    assert_eq!(r.counters.readback_operations, 1);
    sync(&mut r, &mut data, &mut changes);
    // CPU patch while a draw remains pending is merged before the next draw.
    deferred(
        &mut r,
        &mut c,
        &[0x20010485, 0x40030006],
        &map,
        &mut data,
        &mut changes,
    );
    data[0xb000..0xb004].copy_from_slice(&[7, 8, 9, 10]);
    changes.mark_write(GuestAddress(0xb000), 4).unwrap();
    deferred(
        &mut r,
        &mut c,
        &[0x20010485, 0x40030006],
        &map,
        &mut data,
        &mut changes,
    );
    let frame = sync(&mut r, &mut data, &mut changes);
    assert_eq!(&frame.rgba[..4], [7, 8, 9, 10]);
    // New epoch makes pending backing identity ambiguous: fail without guest writes.
    deferred(
        &mut r,
        &mut c,
        &[0x20010485, 0x40030006],
        &map,
        &mut data,
        &mut changes,
    );
    let before = data[0xb000..0xb000 + SIZE].to_vec();
    let mut unknown = TextureChanges::new(2);
    assert!(
        r.synchronize_target(
            &mut SliceMemoryMut {
                base: GuestAddress(0),
                bytes: &mut data
            },
            &mut unknown
        )
        .is_err()
    );
    assert_eq!(&data[0xb000..0xb000 + SIZE], before);
    sync(&mut r, &mut data, &mut changes);
}

#[test]
#[ignore = "requires actual GPU; run explicitly"]
fn gpu_output_as_texture_alias_requires_one_feedback_barrier() {
    let (mut data, mut map, words, image) = fixture();
    let mut changes = TextureChanges::new(1);
    let mut r = Renderer::new().unwrap();
    let mut c = Channel::default();
    // This is a byte-alias/layout reinterpretation, not block-linear RT support.
    map.map(GpuAddress(0xd0000), GuestAddress(RT as u64), 6144)
        .unwrap();
    deferred(&mut r, &mut c, &words, &map, &mut data, &mut changes);
    data[4..8].copy_from_slice(&0xd0000u32.to_le_bytes());
    changes.mark_write(GuestAddress(4), 4).unwrap();
    let before = r.counters;
    deferred(
        &mut r,
        &mut c,
        &[0x20010485, 0x40030006],
        &map,
        &mut data,
        &mut changes,
    );
    assert_eq!(r.counters.coherence_barriers - before.coherence_barriers, 1);
    assert_eq!(
        r.counters.readback_operations - before.readback_operations,
        1
    );
    check(&data[RT..RT + SIZE], &image);
    // Independent scalar GOB oracle interprets the published target's raw bytes.
    let mut sampled = vec![0; 37 * 19 * 4];
    for y in 0..19 {
        for x in 0..37 * 4 {
            sampled[y * 37 * 4 + x] = data[RT + gob_address(x, y, 37 * 4, 4)];
        }
    }
    let frame = sync(&mut r, &mut data, &mut changes);
    check(&frame.rgba, &sampled);
}

struct RejectWrite<'a> {
    bytes: &'a mut [u8],
}
impl GuestMemory for RejectWrite<'_> {
    fn read(&self, a: GuestAddress, n: usize) -> wl_gpu::Result<&[u8]> {
        self.bytes
            .get(a.0 as usize..a.0 as usize + n)
            .ok_or_else(|| wl_gpu::Error("short test read".into()))
    }
}
impl GuestMemoryWrite for RejectWrite<'_> {
    fn validate_write(&self, a: GuestAddress, n: usize) -> wl_gpu::Result<()> {
        self.read(a, n).map(|_| ())
    }
    fn write(&mut self, _: GuestAddress, _: &[u8]) -> wl_gpu::Result<()> {
        Err(wl_gpu::Error("injected atomic write rejection".into()))
    }
}
#[test]
#[ignore = "requires actual GPU; run explicitly"]
fn failed_atomic_writeback_keeps_pending_output_retryable() {
    let (mut data, map, words, image) = fixture();
    let mut changes = TextureChanges::new(1);
    let mut r = Renderer::new().unwrap();
    let mut c = Channel::default();
    deferred(&mut r, &mut c, &words, &map, &mut data, &mut changes);
    let stamp = changes.stamp(RT as u64..(RT + SIZE) as u64);
    let before = data[RT..RT + SIZE].to_vec();
    assert!(
        r.synchronize_target(&mut RejectWrite { bytes: &mut data }, &mut changes)
            .is_err()
    );
    assert_eq!(changes.stamp(RT as u64..(RT + SIZE) as u64), stamp);
    assert_eq!(&data[RT..RT + SIZE], before);
    assert!(r.execute(52, 29, &[]).is_err());
    let frame = sync(&mut r, &mut data, &mut changes);
    check(&frame.rgba, &image);
    // Eviction loses the exact CPU patch history; reject instead of overwriting it.
    deferred(
        &mut r,
        &mut c,
        &[0x20010485, 0x40030006],
        &map,
        &mut data,
        &mut changes,
    );
    for _ in 0..66 {
        changes.mark_write(GuestAddress(0xd000), 4).unwrap();
    }
    let before = data[RT..RT + SIZE].to_vec();
    assert!(
        r.synchronize_target(
            &mut SliceMemoryMut {
                base: GuestAddress(0),
                bytes: &mut data
            },
            &mut changes
        )
        .is_err()
    );
    assert_eq!(&data[RT..RT + SIZE], before);
}
